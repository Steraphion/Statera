"""Collaudo Fase 4.4: blocco con PIN e impronta (autenticatore virtuale di Chrome, dati di esempio)."""
import asyncio, re
from playwright.async_api import async_playwright
BASE = "http://localhost:4173"
PIN = "274913"
results = []
def check(name, ok, info=""):
    results.append(ok); print(("PASS " if ok else "FAIL ") + name + (f"  [{info}]" if info and not ok else ""))
async def hide_show(pg, ms=0):
    await pg.evaluate("Object.defineProperty(document,'visibilityState',{value:'hidden',configurable:true}); document.dispatchEvent(new Event('visibilitychange'))")
    if ms: await pg.wait_for_timeout(ms)
    await pg.evaluate("Object.defineProperty(document,'visibilityState',{value:'visible',configurable:true}); document.dispatchEvent(new Event('visibilitychange'))")
    await pg.wait_for_timeout(300)
async def locked(pg):
    return await pg.locator("dialog.lock[open]").count() == 1
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome")
        for label, opts in [("Android", {**p.devices["Pixel 7"]}), ("PC", {"viewport": {"width": 1366, "height": 800}})]:
            print(f"\n===== {label} =====")
            ctx = await b.new_context(**opts, locale="it-IT"); pg = await ctx.new_page(); errs = []
            pg.on("pageerror", lambda e: errs.append(str(e))); pg.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
            cdp = await ctx.new_cdp_session(pg)
            await cdp.send("WebAuthn.enable")
            await cdp.send("WebAuthn.addVirtualAuthenticator", {"options": {"protocol": "ctap2", "transport": "internal", "hasResidentKey": True, "hasUserVerification": True, "isUserVerified": True, "automaticPresenceSimulation": True}})
            await pg.goto(BASE + "/#/conti"); await pg.wait_for_selector("nav"); await pg.wait_for_timeout(400)
            await pg.get_by_role("button", name="Conto").first.click()
            await pg.get_by_label("Nome").fill("Conto"); await pg.get_by_label("Tipo").select_option("conto_corrente"); await pg.get_by_label("Saldo iniziale (€)").fill("1000")
            await pg.get_by_role("button", name="Salva").click(); await pg.wait_for_timeout(300)
            await pg.goto(BASE + "/#/altro"); await pg.wait_for_timeout(400)
            check(f"{label}: senza blocco l'app si apre", not await locked(pg))
            await pg.get_by_role("button", name="Attiva il blocco").click()
            await pg.get_by_label("PIN (da 4 a 8 cifre)").fill("123456"); await pg.get_by_label("Ripeti il PIN").fill("123456")
            await pg.get_by_role("button", name="Attiva", exact=True).click(); await pg.wait_for_timeout(300)
            check(f"{label}: PIN prevedibile rifiutato", "sequenza" in await pg.get_by_role("alert").inner_text())
            await pg.get_by_label("PIN (da 4 a 8 cifre)").fill(PIN); await pg.get_by_label("Ripeti il PIN").fill("274910")
            await pg.get_by_role("button", name="Attiva", exact=True).click(); await pg.wait_for_timeout(300)
            check(f"{label}: PIN diversi rifiutati", "non coincidono" in await pg.get_by_role("alert").inner_text())
            await pg.get_by_label("Ripeti il PIN").fill(PIN)
            await pg.get_by_role("button", name="Attiva", exact=True).click(); await pg.wait_for_timeout(1500)
            check(f"{label}: blocco attivo", await pg.get_by_text("Attivo", exact=True).count() == 1)
            stored = await pg.evaluate("localStorage.getItem('statera.blocco')")
            check(f"{label}: il PIN non è salvato in chiaro", stored and PIN not in stored)
            # impronta
            check(f"{label}: impronta disponibile", await pg.get_by_role("button", name="Usa anche l'impronta").count() == 1)
            await pg.get_by_role("button", name="Usa anche l'impronta").click()
            await pg.get_by_label("PIN", exact=True).fill(PIN)
            await pg.get_by_role("button", name="Continua").click(); await pg.wait_for_timeout(2000)
            check(f"{label}: impronta attivata", "impronta attiva" in await pg.locator(".status").inner_text())
            # blocca ora
            await pg.get_by_role("button", name="Blocca ora").click(); await pg.wait_for_timeout(300)
            check(f"{label}: schermata di blocco", await locked(pg))
            vis = await pg.evaluate("[getComputedStyle(document.querySelector('.app-root')).visibility, document.querySelector('.app-root').inert]")
            check(f"{label}: contenuto nascosto e inattivo", vis == ["hidden", True], str(vis))
            check(f"{label}: dopo 'Blocca ora' l'impronta non parte da sola", await pg.get_by_role("button", name="Usa l'impronta").count() == 1)
            await pg.get_by_role("button", name="Usa l'impronta").click(); await pg.wait_for_timeout(1500)
            check(f"{label}: 'Usa l'impronta' sblocca", not await locked(pg))
            await pg.get_by_role("button", name="Blocca ora").click(); await pg.wait_for_timeout(300)
            await pg.get_by_label("PIN").fill("111112"); await pg.wait_for_timeout(1500)
            check(f"{label}: PIN sbagliato", "PIN sbagliato" in await pg.get_by_role("alert").inner_text() and await locked(pg))
            await pg.get_by_label("PIN").fill(PIN); await pg.wait_for_timeout(1500)
            check(f"{label}: PIN giusto sblocca (all'ultima cifra)", not await locked(pg))
            # riavvio con impronta: si sblocca da sola (autenticatore virtuale)
            await pg.reload(); await pg.wait_for_timeout(2500)
            check(f"{label}: all'avvio l'impronta sblocca", not await locked(pg))
            # senza impronta: all'avvio serve il PIN
            await pg.goto(BASE + "/#/altro"); await pg.wait_for_timeout(300)
            await pg.get_by_role("button", name="Non usare l'impronta").click(); await pg.wait_for_timeout(300)
            await pg.reload(); await pg.wait_for_timeout(1200)
            check(f"{label}: all'avvio chiede il PIN", await locked(pg) and await pg.get_by_role("button", name="Usa l'impronta").count() == 0)
            await pg.get_by_label("PIN").fill(PIN); await pg.wait_for_timeout(1500)
            check(f"{label}: sbloccata", not await locked(pg))
            # in background meno del tempo scelto: resta aperta; "Subito": si blocca
            await hide_show(pg)
            check(f"{label}: con 1 minuto, un'uscita breve non blocca", not await locked(pg))
            await pg.locator("select").filter(has=pg.locator("option", has_text="subito")).select_option("0"); await pg.wait_for_timeout(200)
            # un inserimento a metà non va perso
            await pg.goto(BASE + "/#/movimenti"); await pg.wait_for_timeout(300)
            await pg.get_by_role("button", name=re.compile("^(Nuovo movimento|Movimento)$")).first.click(); await pg.wait_for_selector("dialog[open]")
            await pg.get_by_label("Importo (€)").fill("23,40")
            await hide_show(pg)
            check(f"{label}: 'Subito' blocca appena si lascia l'app", await locked(pg))
            top = await pg.evaluate("(() => { const el = document.elementFromPoint(innerWidth / 2, 120); return !!el && !!el.closest('dialog.lock') })()")
            check(f"{label}: il blocco copre anche un modulo aperto", top)
            await pg.keyboard.press("Escape"); await pg.wait_for_timeout(300)
            check(f"{label}: Esc non chiude il blocco", await locked(pg))
            await pg.get_by_label("PIN").fill(PIN); await pg.wait_for_timeout(1500)
            check(f"{label}: inserimento a metà ancora lì", not await locked(pg) and await pg.get_by_label("Importo (€)").input_value() == "23,40")
            await pg.keyboard.press("Escape"); await pg.wait_for_timeout(300)
            # cambio PIN
            await pg.goto(BASE + "/#/altro"); await pg.wait_for_timeout(300)
            await pg.get_by_role("button", name="Cambia PIN").click()
            await pg.get_by_label("PIN attuale").fill("000001"); await pg.get_by_label("Nuovo PIN").fill("8642"); await pg.get_by_label("Ripeti il PIN").fill("8642")
            await pg.get_by_role("button", name="Cambia PIN", exact=True).last.click(); await pg.wait_for_timeout(1500)
            check(f"{label}: cambio con PIN attuale sbagliato rifiutato", "sbagliato" in await pg.get_by_role("alert").inner_text())
            await pg.get_by_label("PIN attuale").fill(PIN)
            await pg.get_by_role("button", name="Cambia PIN", exact=True).last.click(); await pg.wait_for_timeout(2000)
            await pg.get_by_role("button", name="Blocca ora").click(); await pg.wait_for_timeout(300)
            await pg.get_by_label("PIN").fill("8642"); await pg.wait_for_timeout(1500)
            check(f"{label}: nuovo PIN funziona", not await locked(pg))
            # troppi tentativi, poi PIN dimenticato
            await pg.get_by_role("button", name="Blocca ora").click(); await pg.wait_for_timeout(300)
            for _ in range(5):
                await pg.get_by_label("PIN").fill("1357"); await pg.wait_for_timeout(1200)
            msg = await pg.get_by_role("alert").inner_text()
            check(f"{label}: dopo 5 errori bisogna aspettare", "riprova tra" in msg, msg)
            await pg.get_by_label("PIN").fill("8642"); await pg.wait_for_timeout(1200)
            check(f"{label}: durante l'attesa neanche il PIN giusto sblocca", await locked(pg))
            await pg.get_by_role("button", name="Ho dimenticato il PIN").click()
            await pg.get_by_role("button", name="Elimina i dati di questo dispositivo").click()
            await pg.get_by_role("button", name="Conferma: elimina i dati").click(); await pg.wait_for_timeout(2500)
            check(f"{label}: dopo l'eliminazione niente blocco", not await locked(pg) and await pg.evaluate("localStorage.getItem('statera.blocco')") is None)
            check(f"{label}: dati del dispositivo eliminati", await pg.get_by_text("Benvenuto in Statera").count() == 1)
            # disattivazione
            await pg.goto(BASE + "/#/altro"); await pg.wait_for_timeout(300)
            await pg.get_by_role("button", name="Attiva il blocco").click()
            await pg.get_by_label("PIN (da 4 a 8 cifre)").fill("9753"); await pg.get_by_label("Ripeti il PIN").fill("9753")
            await pg.get_by_role("button", name="Attiva", exact=True).click(); await pg.wait_for_timeout(1500)
            await pg.get_by_role("button", name="Disattiva").click()
            await pg.get_by_label("PIN", exact=True).fill("9753")
            await pg.get_by_role("button", name="Disattiva", exact=True).last.click(); await pg.wait_for_timeout(1500)
            await pg.reload(); await pg.wait_for_timeout(1000)
            check(f"{label}: disattivato, si apre senza PIN", not await locked(pg) and await pg.get_by_role("button", name="Attiva il blocco").count() == 1)
            check(f"{label}: nessun errore in console", not errs, "; ".join(errs[:3]))
            await ctx.close()
        await b.close()
    print(f"\n{sum(results)}/{len(results)} controlli superati")
asyncio.run(main())
